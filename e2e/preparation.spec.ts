import {expect,test} from '@playwright/test'

test('starter selection adapts to topics and audience while the brief retains selections',async({page})=>{
 await page.goto('/questions')
 const workspace=page.getByRole('region',{name:'Questions workspace'})
 await expect(page.getByRole('button',{name:'Starter selection',exact:true})).toHaveAttribute('aria-pressed','true')
 await expect(page.getByRole('button',{name:'+ Add to brief',exact:true})).toHaveCount(5)
 await expect(page.getByRole('complementary',{name:'Your brief'})).toHaveCount(0)
 await page.getByRole('button',{name:'+ Add to brief',exact:true}).first().click()
 await page.getByRole('button',{name:'Data and privacy',exact:true}).click()
 await expect(workspace.getByRole('button',{name:'+ Add to brief',exact:true}).first()).toBeVisible()
 await workspace.getByRole('button',{name:'Executive',exact:true}).click()
 await workspace.getByRole('button',{name:'+ Add to brief',exact:true}).first().click()
 await workspace.getByRole('button',{name:'Browse all',exact:true}).click()
 await expect(workspace.getByRole('button',{name:'Browse all',exact:true})).toHaveAttribute('aria-pressed','true')
 if(test.info().project.name==='mobile')await page.getByRole('button',{name:/Your brief · 2/}).click()
 else await page.getByRole('complementary',{name:'Your brief'}).getByRole('button',{name:'Review / export'}).click()
 const brief=page.getByRole('dialog',{name:'Your meeting brief'})
 await expect(brief.locator('.brief-questions>li')).toHaveCount(2)
 await expect(brief).toContainText('Board')
 await expect(brief).toContainText('Executive')
 await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
})

test('Updates interleaves dates and reveals questions and limits on demand',async({page})=>{
 await page.goto('/questions')
 await page.getByRole('button',{name:'What’s new',exact:true}).click()
 const news=page.getByRole('dialog',{name:'What’s new'})
 await expect(news).toBeVisible()
 const dates=await news.locator('.news-card> .news-meta time').evaluateAll(nodes=>nodes.map(n=>n.getAttribute('datetime')))
 expect(dates.length).toBeGreaterThan(0)
 expect(dates).toEqual([...dates].sort().reverse())
 const details=news.locator('.news-card').first().locator('details').first()
 await expect(details).not.toHaveAttribute('open','')
 await details.getByText('Questions and supporting detail', {exact:true}).click()
 await expect(details.getByRole('button',{name:'+ Add to brief',exact:true})).toBeVisible()
 await news.getByRole('button',{name:'Priority',exact:true}).click()
 await expect(news).toContainText('Editorial order, not an applicability assessment.')
 await news.getByRole('button',{name:'Close What’s new'}).click()
 await page.getByRole('button',{name:'What’s new',exact:true}).click()
 await expect(news.getByRole('button',{name:'Priority',exact:true})).toHaveAttribute('aria-pressed','true')
 await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
})
