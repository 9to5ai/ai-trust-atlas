import {expect,test} from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

test('questions are visible before scrolling, with supporting detail on demand',async({page})=>{
 await page.goto('/questions')
 const workspace=page.getByRole('region',{name:'Questions workspace'})
 await expect(workspace.getByRole('heading',{level:1,name:'Questions',exact:true})).toBeVisible()
 const card=workspace.getByRole('article').first()
 await expect(card.getByRole('heading',{level:2})).toBeInViewport({ratio:1})
 await expect(card.getByRole('button',{name:'+ Add to brief',exact:true})).toBeInViewport({ratio:1})
 await expect(workspace.getByRole('button',{name:/Review brief/})).toHaveCount(0)
 await expect(card.getByRole('heading',{name:'What to ask for'})).not.toBeVisible()
 await card.locator('summary').click()
 await expect(card.getByRole('heading',{name:'What to ask for'})).toBeVisible()
 await expect(card.getByRole('heading',{name:'If the answer is vague…'})).toBeVisible()
 await expect(card.getByRole('button',{name:'Read context →'})).toBeVisible()
 await card.locator('summary').click()
 await expect(card.getByRole('heading',{name:'What to ask for'})).not.toBeVisible()
 await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
})

test('compact filters preserve topic choices, the full catalogue and saved brief',async({page})=>{
 await page.goto('/questions')
 const workspace=page.getByRole('region',{name:'Questions workspace'})
 await expect(workspace.getByRole('button',{name:'+ Add to brief',exact:true})).toHaveCount(5)
 await workspace.getByRole('button',{name:'+ Add to brief',exact:true}).first().click()
 await workspace.locator('.questions-topic-picker>summary').click()
 await workspace.getByRole('checkbox',{name:'Data and privacy',exact:true}).check()
 await workspace.getByRole('checkbox',{name:'Security',exact:true}).check()
 await workspace.getByRole('button',{name:'Done',exact:true}).click()
 await expect(workspace.locator('.questions-topic-picker>summary')).toContainText('Topics · 2')
 await workspace.getByRole('combobox',{name:'Question audience'}).selectOption('executive')
 await workspace.getByRole('button',{name:'+ Add to brief',exact:true}).first().click()
 await workspace.getByRole('button',{name:'Browse all questions',exact:false}).click()
 await expect(workspace.getByRole('button',{name:/Back to suggested questions/})).toBeVisible()
 await workspace.locator('.questions-topic-picker>summary').click()
 await expect(workspace.getByRole('checkbox',{name:'Data and privacy'})).toBeChecked()
 await expect(workspace.getByRole('checkbox',{name:'Security',exact:true})).toBeChecked()
 await workspace.locator('.questions-topic-picker>summary').press('Escape')
 await expect(workspace.getByRole('checkbox',{name:'Data and privacy'})).not.toBeVisible()
 await page.reload()
 await expect(workspace.getByRole('combobox',{name:'Question audience'})).toHaveValue('executive')
 await workspace.getByRole('button',{name:/Review brief · 2/}).click()
 const brief=page.getByRole('dialog',{name:'Your meeting brief'})
 await expect(brief.locator('.brief-questions>li')).toHaveCount(2)
 await expect(brief).toContainText('Board')
 await expect(brief).toContainText('Executive')
 await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
})

test('Updates interleaves dates and reveals questions and limits on demand',async({page})=>{
 await page.goto('/questions')
 await page.getByRole('button',{name:'What’s new',exact:true}).click()
 const news=page.getByRole('dialog',{name:'What’s new'})
 await expect(news).toBeVisible()
 const dates=await news.locator('.news-card> .news-meta time').evaluateAll(nodes=>nodes.map(n=>n.getAttribute('datetime')))
 expect(dates.length).toBeGreaterThan(0)
 expect(dates).toEqual([...dates].sort().reverse())
 const first=news.locator('.news-card').first()
 // The first update is readable immediately, even on a narrow phone.
 const heading=await first.locator('h3').boundingBox()
 expect(heading!.y+heading!.height).toBeLessThan(page.viewportSize()!.height*.6)
 await expect(news.getByRole('combobox',{name:'Questions for'})).toHaveCount(0)
 const closedAudit=await new AxeBuilder({page}).include('.whats-new').analyze()
 expect(closedAudit.violations.filter(v=>v.impact==='serious'||v.impact==='critical')).toEqual([])
 const details=first.locator('details').first()
 await expect(details).not.toHaveAttribute('open','')
 await details.locator('summary').first().click()
 await expect(details.getByRole('button',{name:'+ Add to brief',exact:true})).toBeVisible()
 const expandedAudit=await new AxeBuilder({page}).include('.whats-new').analyze()
 expect(expandedAudit.violations.filter(v=>v.impact==='serious'||v.impact==='critical')).toEqual([])
 await details.getByRole('combobox',{name:'Questions for'}).selectOption('assurance')
 await details.getByRole('button',{name:'+ Add to brief',exact:true}).click()
 await details.getByRole('combobox',{name:'Questions for'}).selectOption('executive')
 await details.getByRole('button',{name:'Review brief · 1',exact:true}).click()
 const brief=page.getByRole('dialog',{name:'Your meeting brief'})
 await expect(brief).toContainText('Internal audit & assurance')
 await brief.getByRole('button',{name:'Close meeting brief'}).click()
 await news.getByRole('combobox',{name:'Updates order'}).selectOption('priority')
 await expect(news).toContainText('Editorial order, not an applicability assessment.')
 await news.getByRole('button',{name:'Close What’s new'}).click()
 await page.getByRole('button',{name:'What’s new',exact:true}).click()
 await expect(news.getByRole('combobox',{name:'Updates order'})).toHaveValue('priority')
 await news.getByRole('combobox',{name:'Time period'}).selectOption('120')
 await expect(news.getByRole('heading',{name:'OWASP updates its LLM security guide for 2026'})).toBeVisible()
 await expect.poll(()=>news.evaluate(el=>el.scrollWidth<=el.clientWidth)).toBe(true)
 await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
})
